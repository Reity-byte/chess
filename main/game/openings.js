// For a SAN list (check suffixes allowed): the deepest named opening the game
// fully follows, and how many plies from the start are still "book".
function identifyOpening(sanMoves, extraBookLines = []) {
    const played = sanMoves.map(s => s.replace(/[+#]$/, ''));
    const lines = OPENING_LINES.concat(extraBookLines.map(moves => ({ name: null, moves })));
    let name = null, namedLength = 0, bookPlies = 0;
    for (const line of lines) {
        let k = 0;
        while (k < line.moves.length && k < played.length && line.moves[k] === played[k]) k++;
        if (k > bookPlies) bookPlies = k;
        if (line.name && k === line.moves.length && k > namedLength) { name = line.name; namedLength = k; }
    }
    return { name, bookPlies };
}
