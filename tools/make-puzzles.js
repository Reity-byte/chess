// Builds the bundled puzzle library (main/game/puzzle-library.js) from
// engine-vs-engine games: weaker, human-like levels make real mistakes, and the
// positions where a mistake hands the other side a clear, unique win become
// puzzles (see tools/puzzle-miner.js).
//
//   node tools/make-puzzles.js [games=120] [workers=cpus-2]
//
// Workers write their finds to tools/.puzzles/*.jsonl as they go, so a run can
// be stopped and resumed; `node tools/make-puzzles.js --write` only rebuilds
// the library file from what was found so far.
const fs = require('fs');
const path = require('path');
const os = require('os');
const { fork } = require('child_process');
const { ROOT, loadAnalysisWorker, MATCH_OPENINGS } = require('../tests/lib');

const OUT_DIR = path.join(__dirname, '.puzzles');
const LIBRARY = path.join(ROOT, 'main', 'game', 'puzzle-library.js');
const LIBRARY_SIZE = 500;
const RATING_LOW = 450, RATING_HIGH = 2300;

// ─── WORKER ────────────────────────────────────────────────────────────────────
if (process.env.PUZZLE_WORKER) {
    const w = loadAnalysisWorker();
    w.run(fs.readFileSync(path.join(ROOT, 'main', 'game', 'strength.js'), 'utf8'));
    w.run(fs.readFileSync(path.join(__dirname, 'puzzle-miner.js'), 'utf8'));
    const id = +process.env.PUZZLE_WORKER;
    const games = +process.env.PUZZLE_GAMES;
    const file = path.join(OUT_DIR, `w${id}-${Date.now()}.jsonl`);
    for (let g = 0; g < games; g++) {
        // Mostly club-level sides (blunders that leave real tactics), some
        // stronger ones for harder finds.
        const pick = () => 3 + Math.floor(Math.random() * 9); // ENGINE_LEVELS 3..11
        const levels = { white: pick(), black: pick() };
        const opening = MATCH_OPENINGS[Math.floor(Math.random() * MATCH_OPENINGS.length)];
        const t0 = Date.now();
        const sans = w.run(`minerGame({ white: ENGINE_LEVELS[${levels.white}], black: ENGINE_LEVELS[${levels.black}] }, ${JSON.stringify(opening)})`);
        const found = w.run(`minerPuzzles(${JSON.stringify(sans)})`);
        for (const p of found) fs.appendFileSync(file, JSON.stringify(p) + '\n');
        process.send({ id, game: g, plies: sans.length, found: found.length, secs: Math.round((Date.now() - t0) / 1000), stats: w.run('MINER_STATS') });
    }
    process.exit(0);
}

// ─── LIBRARY FILE ──────────────────────────────────────────────────────────────
function readFinds() {
    if (!fs.existsSync(OUT_DIR)) return [];
    const out = [];
    for (const f of fs.readdirSync(OUT_DIR).filter(f => f.endsWith('.jsonl'))) {
        for (const line of fs.readFileSync(path.join(OUT_DIR, f), 'utf8').split('\n')) {
            if (line.trim()) try { out.push(JSON.parse(line)); } catch (e) { /* partial last line */ }
        }
    }
    return out;
}

function writeLibrary() {
    const w = loadAnalysisWorker();
    const seen = new Set();
    const finds = [];
    for (const p of readFinds()) {
        const key = w.run(`replaySANFromStart(${JSON.stringify(p.prefix)}); getBoardKey()`);
        if (seen.has(key)) continue;
        seen.add(key);
        finds.push(p);
    }
    // Keep a spread of themes: mates and forks first, then the rest by rating band.
    const score = (p) => (p.themes.includes('mate') ? 2 : 0) + (p.themes.includes('fork') ? 1 : 0) + Math.random();
    finds.sort((a, b) => score(b) - score(a));
    const keep = finds.slice(0, LIBRARY_SIZE);
    // The miner's ratings are only a difficulty order (and bunch up low: engine
    // mistakes are mostly simple), so spread that order over a rating ladder —
    // Puzzle Rush needs puzzles all the way up. Ties: longer lines rank harder.
    keep.forEach(p => { p.tie = Math.random(); });
    keep.sort((a, b) => a.rating - b.rating || a.solution.length - b.solution.length || a.tie - b.tie);
    keep.forEach((p, i) => {
        const t = keep.length > 1 ? i / (keep.length - 1) : 0;
        p.rating = Math.round((RATING_LOW + (RATING_HIGH - RATING_LOW) * Math.pow(t, 1.1)) / 10) * 10;
    });
    const lines = keep.map((p, i) => `    { id: 'L${String(i + 1).padStart(3, '0')}', rating: ${p.rating}, themes: ${JSON.stringify(p.themes)},\n`
        + `      prefix: ${JSON.stringify(p.prefix.join(' '))},\n      solution: ${JSON.stringify(p.solution.join(' '))} },`);
    fs.writeFileSync(LIBRARY, `// GENERATED by tools/make-puzzles.js — engine-mined tactics from engine-vs-engine
// games. prefix: the game up to and including the opponent's mistake (the page
// shows the position before it, then plays it); solution: the solver's moves
// alternating with the forced replies, starting with the solver.
const PUZZLE_LIBRARY = [
${lines.join('\n')}
];
`);
    const count = {};
    for (const p of keep) for (const t of p.themes) count[t] = (count[t] || 0) + 1;
    console.log(`${finds.length} unique finds, wrote ${keep.length} to ${path.relative(ROOT, LIBRARY)}`);
    console.log(count);
    const bands = {};
    for (const p of keep) { const b = Math.floor(p.rating / 200) * 200; bands[b] = (bands[b] || 0) + 1; }
    console.log(bands);
}

// ─── MAIN ──────────────────────────────────────────────────────────────────────
if (process.argv.includes('--write')) {
    writeLibrary();
} else {
    const totalGames = +(process.argv[2] || 120);
    const workers = +(process.argv[3] || Math.max(1, os.cpus().length - 2));
    fs.mkdirSync(OUT_DIR, { recursive: true });
    let running = workers, found = 0, played = 0;
    const t0 = Date.now();
    for (let i = 0; i < workers; i++) {
        const games = Math.floor(totalGames / workers) + (i < totalGames % workers ? 1 : 0);
        const child = fork(__filename, [], { env: { ...process.env, PUZZLE_WORKER: String(i), PUZZLE_GAMES: String(games) } });
        child.on('message', (m) => {
            played++; found += m.found;
            console.log(`[${Math.round((Date.now() - t0) / 1000)}s] worker ${m.id} game ${m.game + 1}: ${m.plies} plies, ${m.found} puzzles (${m.secs}s) — total ${found} from ${played} games`);
        });
        child.on('exit', () => { if (--running === 0) writeLibrary(); });
    }
}
